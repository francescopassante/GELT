"""τ_int of Ō and the block-size stability of the 0⁺⁺ errors — the supervisor's S3,
tasks 1 and 2 (notes/prof_notes.md), SU(2) half.

Every SU(2) error in the glueball chapter is a delete-block jackknife with
block b = 10 on the 400 chain-ordered test configurations (40 blocks). n_skip = 5
was calibrated on a smaller isotropic lattice, so b = 10 has to be justified on
the production chains themselves. Two routes, both offline from the tracked
``dumps/*_test_obars.pt`` (the test split is contiguous and chain-ordered, so a
dump's row order *is* Monte Carlo time):

1. **τ_int** (Madras–Sokal, ``gelt.sampler.integrated_autocorrelation_time``,
   c = 6) of Ō(t) averaged over t, per configuration, for the thin plaquette
   operator, APE×6, the GEVP-projected operator (v₀ from the full sample) and
   GELT — all on the same 400 test configurations, so the four are read on one
   footing. Beside it, τ_int of the per-configuration contribution to C(1),
   c_i = ⟨d_i(t) d_i(t+1)⟩_t with d = Ō − ⟨Ō⟩ (the vacuum of
   ``connected_correlator``): m_eff(1) is built from C(1), and a product of
   fluctuations can decorrelate at a different rate from the fluctuation itself.
   The error on τ_int is Madras–Sokal's σ_τ ≈ τ √(2(2W + 1)/N).

2. **σ(b)** for b ∈ {1, 2, 5, 10, 20, 40} (400 … 10 blocks) on m_eff(1), the
   cosh-fit m and A₀ (GELT and GEVP-projected), ΔA₀ and Δm_eff(1). The
   estimator is **imported** from ``fit_glueball_overlap`` (``fit_one`` on
   [2, 7], ``project_ground`` refitted in every sample), and the diagonal fit
   weights σ_Δ are held at the production block for every b — so the central
   values are identical across b and only the error moves, which is the
   question. The b = 10 column is gated on reproducing the record's
   per-ensemble ΔA₀ and Δm_eff(1) (notes/thesis_record.md §3.2).

   A jackknife error from n blocks is itself uncertain by ≈ 1/√(2(n − 1)) of
   itself: 16% at b = 20, 24% at b = 40. That is the band drawn around 1 in
   the figure.

Reading (notes/prof_notes.md S3, fixed before the numbers existed, made
operational here before they were computed): b = 10 is **on the plateau** for a
quantity unless the ensemble-averaged ratio σ(b)/σ(10) exceeds 1 by more than
its noise, δ_b/√n_ens, at **both** b = 20 and b = 40 — a real rise is monotone
in b, a single excursion at 10 or 20 blocks is noise. If a quantity is flagged,
its errors are re-quoted at the plateau, max(σ(20), σ(40)) per ensemble (the
conservative choice), and the combined ΔA₀ is recomputed from those. Also
required: b = 10 ≥ 2 τ_int for every operator.

Writes ``results/glueball/block_size_scan.{pt,tex,png}`` and ``…_rho.png``;
the .tex holds two tabulars (τ_int, then σ(b)), both regenerated by every run.
The .pt keeps ρ(t) up to ``RHO_MAX_LAG`` for every series whose τ_int is
tabulated, so the autocorrelation function behind each τ_int can be re-read
offline — a slow tail the Sokal window cut off is visible there and not in τ.

Offline, seconds, no GPU.

Run:
    python scripts/block_size_scan.py [dump.pt ...]
"""

