def _tv(v, dig=2):
    return f"${v[0]:.{dig}f}({round(v[1] * 10**dig)})$"


def table(per, comb, stem):
    tau_cols = [("thin", "thin"), ("ape", r"APE$\times6$"), ("gevp", "GEVP"), ("gelt", "GELT"),
                ("c1_gevp", r"$c_1$ GEVP"), ("c1_gelt", r"$c_1$ GELT")]
    lines = [
        "% block_size_scan.py — S3 of notes/prof_notes.md. tau_int (Madras-Sokal, c = 6)",
        "% of Obar averaged over t, per test configuration, in saved configurations;",
        "% c_1 = the per-configuration contribution to C(1). 400 chain-ordered test configs.",
        r"\begin{tabular}{l" + "c" * len(tau_cols) + "}", r"\toprule",
        "ensemble & " + " & ".join(c for _, c in tau_cols) + r" \\", r"\midrule",
    ]
    for tag, res in per.items():
        lines.append(tag + " & " + " & ".join(_tv(res["taus"][k][:2]) for k, _ in tau_cols)
                     + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", "", ""]

    cols = ["meff1_g", "meff1_p", "m_g", "m_p", "A0_g", "A0_p", "dA0"]
    head = [r"$m_\mathrm{eff}^{G}(1)$", r"$m_\mathrm{eff}^{P}(1)$", r"$m^{G}$", r"$m^{P}$",
            r"$A_0^{G}$", r"$A_0^{P}$", r"$\Delta A_0$"]
    lines += [
        "% sigma(b): blocked-jackknife error at block size b (fit weights fixed at b = 10,",
        "% so the central values do not move). G = GELT, P = GEVP-projected.",
        r"\begin{tabular}{rr" + "c" * len(cols) + "}", r"\toprule",
        r"$b$ & blocks & " + " & ".join(head) + r" \\",
    ]
    for tag, res in per.items():
        lines += [r"\midrule", rf"\multicolumn{{{2 + len(cols)}}}{{l}}{{\emph{{{tag}}}}} \\"]
        for b in BLOCKS:
            row = [f"{res['sigma'][b][k][1]:.4f}" for k in cols]
            if b == PRODUCTION:
                row = [rf"\textbf{{{x}}}" for x in row]
            lines.append(f"{b} & {res['n_blocks'][b]} & " + " & ".join(row) + r" \\")
    if len(per) > 1:
        lines += [r"\midrule", rf"\multicolumn{{{2 + len(cols)}}}{{l}}"
                  r"{\emph{combined (inverse variance): $\Delta m_\mathrm{eff}(1)$ in the "
                  r"$m_\mathrm{eff}^{G}(1)$ column, $\Delta A_0$ in the last}} \\"]
        for b in BLOCKS:
            a, d = comb[b]["dA0"], comb[b]["dmeff1"]
            lines.append(f"{b} & & ${d[0]:+.4f}({round(d[1] * 1e4)})$" + " & " * (len(cols) - 1)
                         + f"${a[0]:+.3f}({round(a[1] * 1000)})$" + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    with open(stem + ".tex", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  saved {stem}.tex")


def main():
    if not DUMPS:
        raise SystemExit("no dumps found")
    per = {}
    for path in DUMPS:
        per[_tag(path)] = scan_dump(path)

    print("\nτ_int of Ō averaged over t (saved configurations; 2τ_int must be ≤ "
          f"b = {PRODUCTION}):")
    print(f"  {'':<6}" + "".join(f"{k:>18}" for k in TAU_OPS))
    for tag, res in per.items():
        print(f"  {tag:<6}" + "".join(
            f"{res['taus'][k][0]:>9.2f} ± {res['taus'][k][1]:.2f} " for k in TAU_OPS)
            + "   W = " + ",".join(str(res["taus"][k][2]) for k in TAU_OPS))
    print(f"\nρ(t), t = 1 … 8 (noise ≈ 1/√N):")
    for tag, res in per.items():
        for k in ("thin", "ape", "gevp", "gelt"):
            print(f"  {tag:<6}{k:<6}" + " ".join(f"{r:+.2f}" for r in res["rho"][k][1:9].tolist()))
    worst = max(res["taus"][k][0] + res["taus"][k][1] for res in per.values() for k in TAU_OPS)
    tau_ok = 2 * worst <= PRODUCTION
    print(f"  largest τ_int + σ_τ = {worst:.2f} → 2τ_int {'≤' if tau_ok else '>'} {PRODUCTION}")

    print()
    if not _POSITIONAL:
        gate(per)

    print(f"\nσ(b) per ensemble (fit weights fixed at b = {PRODUCTION}):")
    for tag, res in per.items():
        print(f"  {tag}")
        print(f"    {'b':>3} {'blk':>4}" + "".join(f"{k:>10}" for k in KEYS))
        for b in BLOCKS:
            print(f"    {b:>3} {res['n_blocks'][b]:>4}" + "".join(
                f"{res['sigma'][b][k][1]:>10.4f}" for k in KEYS))
        print(f"    central (identical at every b): " + ", ".join(
            f"{k} {res['sigma'][PRODUCTION][k][0]:+.4f}" for k in KEYS))

    read = reading(per)
    print(f"\nσ(b)/σ({PRODUCTION}), mean over {len(per)} ensembles (± noise δ_b/√n_ens):")
    print(f"  {'':<8}" + "".join(f"{'b=' + str(b):>15}" for b in BLOCKS) + "   verdict")
    for k in KEYS:
        flagged, r = read[k]
        print(f"  {k:<8}" + "".join(f"{r[b][0]:>8.3f} ±{r[b][1]:.3f}" for b in BLOCKS)
              + ("   RISING at b = 10 → re-quote at plateau" if flagged else "   plateau"))

    comb = {b: {k: _combine([res["sigma"][b][k] for res in per.values()]) for k in COMBINED}
            for b in BLOCKS}
    for k in COMBINED:
        print(f"\ncombined {k} (inverse variance) at each b:")
        for b in BLOCKS:
            v = comb[b][k]
            print(f"  b = {b:>2}: {v[0]:+.4f} ± {v[1]:.4f}  ({abs(v[0]) / v[1]:.1f}σ)")

    print("\nτ_int of the b = 1 jackknife pseudo-values (2τ_int ≈ σ²(b→∞)/σ²(1); "
          "½ = uncorrelated):")
    print(f"  {'':<6}" + "".join(f"{k:>14}" for k in KEYS))
    for tag, res in per.items():
        print(f"  {tag:<6}" + "".join(
            f"{res['pseudo_tau'][k][0]:>8.2f}±{res['pseudo_tau'][k][1]:.2f}" for k in KEYS))

    flagged = [k for k in KEYS if read[k][0]]
    requote = {}
    if flagged:
        print(f"\nREADING: rising at b = {PRODUCTION} for {flagged}; plateau errors "
              f"max(σ({PLATEAU[0]}), σ({PLATEAU[1]})):")
        for k in flagged:
            for tag, res in per.items():
                s = max(res["sigma"][b][k][1] for b in PLATEAU)
                requote[(tag, k)] = s
                print(f"  {tag} {k}: {res['sigma'][PRODUCTION][k][1]:.4f} → {s:.4f}")
        if "dA0" in flagged:
            v = _combine([(res["sigma"][PRODUCTION]["dA0"][0], requote[(t, "dA0")])
                          for t, res in per.items()])
            print(f"  combined ΔA₀ at the plateau: {v[0]:+.4f} ± {v[1]:.4f} "
                  f"({v[0] / v[1]:.1f}σ)")
    else:
        print(f"\nREADING: b = {PRODUCTION} is on the plateau for every quantity"
              + ("" if tau_ok else f", BUT 2τ_int > {PRODUCTION} for some operator") + ".")

    stem = OUT
    torch.save({"per": per, "reading": read, "combined": comb, "requote": requote,
                "tau_ok": tau_ok, "dumps": DUMPS}, stem + ".pt")
    print(f"\n  saved {stem}.pt")
    table(per, comb, stem)
    figure(per, read, stem)
    figure_rho(per, stem)


if __name__ == "__main__":
    main()
