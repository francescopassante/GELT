def figure_rho(per, stem):
    """ρ(t) of Ō per ensemble, with the ±1/√N noise band; τ_int and W in the legend."""
    fig, axes = plt.subplots(1, len(per), figsize=(4.0 * len(per), 3.6), sharey=True,
                             facecolor="white", squeeze=False)
    for ax, (tag, res) in zip(axes[0], per.items()):
        noise = 1.0 / math.sqrt(res["B"])
        ax.axhspan(-noise, noise, color=C_BAND, lw=0, zorder=0)
        ax.axhline(0.0, color=C_AXIS, lw=1.0, zorder=1)
        t = list(range(1, RHO_MAX_LAG + 1))
        for k, name, col, mk in RHO_SERIES:
            tt, _, w = res["taus"][k]
            ax.plot(t, res["rho"][k][1:].tolist(), color=col, lw=1.6, marker=mk, ms=4.5,
                    mec="white", mew=0.8, zorder=3,
                    label=rf"{name}: $\tau_\mathrm{{int}}={tt:.2f}$, $W={w}$")
            # The window each τ_int summed up to: a tick on the curve at t = W.
            ax.plot([w], [res["rho"][k][w].item()], marker="o", ms=11, mew=1.4, mfc="none",
                    color=col, zorder=4)
        ax.set_title(tag, color=C_TEXT, fontsize=10)
        ax.set_xlabel(r"$\tau$ (saved configurations)", color=C_TEXT2)
        ax.set_xlim(0.5, RHO_MAX_LAG + 0.5)
        ax.set_xticks([1] + list(range(5, RHO_MAX_LAG + 1, 5)))
        ax.grid(axis="y", color=C_GRID, lw=0.6)
        ax.set_axisbelow(True)
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        for side in ("left", "bottom"):
            ax.spines[side].set_color(C_AXIS)
        ax.tick_params(colors=C_TEXT2, labelsize=8)
        ax.legend(frameon=False, fontsize=7.5, loc="upper right")
    axes[0, 0].set_ylabel(r"$\rho(\tau)$ of $\bar{\mathcal{O}}$", color=C_TEXT2)
    fig.tight_layout()
    fig.savefig(stem + "_rho.png", dpi=200)
    plt.close(fig)
    print(f"  saved {stem}_rho.png")


