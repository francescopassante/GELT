def _tag(dump):
    b = os.path.basename(dump)
    return f"ens{b.split('_ens')[1].split('_')[0]}" if "_ens" in b else "ens0"


def _combine(vals):
    """Inverse-variance mean and error of ``[(x, σ), …]``."""
    w = [1.0 / e**2 for _, e in vals]
    return sum(wi * x for wi, (x, _) in zip(w, vals)) / sum(w), 1.0 / math.sqrt(sum(w))


def err_of_err(n_blocks):
    """Relative uncertainty of a jackknife error from ``n_blocks`` blocks."""
    return 1.0 / math.sqrt(2.0 * (n_blocks - 1))


def jackknife_samples(fn, B, b):
    """The delete-block samples ``fgo.blocked_jackknife`` averages, kept."""
    out = []
    for bl in fgo._blocks(B, b):
        mask = torch.ones(B, dtype=torch.bool)
        mask[bl] = False
        out.append(fn(mask))
    return torch.stack(out)


def tau(series):
    """(τ_int, σ_τ, W) of a scalar chain, Madras–Sokal."""
    x = series.numpy()
    _, t, w = integrated_autocorrelation_time(x, c=SOKAL_C)
    return t, t * math.sqrt(2.0 * (2 * w + 1) / x.size), w


def rho_of(series):
    """ρ(t), t = 0 … RHO_MAX_LAG, of a scalar chain — the function τ_int sums."""
    rho, _, _ = integrated_autocorrelation_time(series.numpy(), c=SOKAL_C, max_lag=RHO_MAX_LAG)
    return torch.from_numpy(rho)


def c1_series(obar):
    """Per-configuration contribution to C(1), with connected_correlator's vacuum."""
    d = obar - obar.mean()
    return (d.roll(-1, dims=1) * d).mean(dim=1)


def scan_dump(path):
    blob = torch.load(path)
    gelt = blob["gelt_obar"].double()
    basis = blob["Obar_basis"].double()
    meta = blob.get("meta", {})
    t0 = int(meta.get("gevp_t0", 1))
    td = t0 + 1 if fgo.GEVP_TD is None else fgo.GEVP_TD
    if int(meta.get("jack_block", PRODUCTION)) != PRODUCTION:
        raise SystemExit(f"{path}: jack_block {meta['jack_block']} ≠ {PRODUCTION}")
    B, _ = gelt.shape
    bad = [b for b in BLOCKS if B % b]
    if bad:
        print(f"  note: B = {B} not divisible by {bad}; the last block is short")
    proj = fgo.project_ground(basis, t0, td)
    print(f"── {os.path.basename(path)} ({_tag(path)}): {B} test configs, "
          f"GEVP (t0, td) = ({t0}, {td})")

    series = {
        "thin": basis[0].mean(dim=1),
        "ape": basis[-1].mean(dim=1),
        "gevp": proj.mean(dim=1),
        "gelt": gelt.mean(dim=1),
        "c1_gevp": c1_series(proj),
        "c1_gelt": c1_series(gelt),
    }
    taus = {k: tau(v) for k, v in series.items()}
    rhos = {k: rho_of(v) for k, v in series.items()}

    # Fit weights fixed at the production block for every b (see docstring).
    _, sig_g = fgo.blocked_jackknife(lambda m: connected_correlator(gelt[m]), B, PRODUCTION)
    _, sig_p = fgo.blocked_jackknife(lambda m: connected_correlator(proj[m]), B, PRODUCTION)

    def stats(mask):
        Cg = connected_correlator(gelt[mask])
        Cp = connected_correlator(fgo.project_ground(basis[:, mask], t0, td))
        m_g, a_g, _ = fgo.fit_one(Cg, sig_g)
        m_p, a_p, _ = fgo.fit_one(Cp, sig_p)
        e_g, e_p = effective_mass(Cg)[1].item(), effective_mass(Cp)[1].item()
        return torch.tensor([e_g, e_p, e_g - e_p, m_g, m_p, m_g - m_p, a_g, a_p, a_g - a_p],
                            dtype=torch.float64)

    sig, pseudo_tau = {}, {}
    for b in BLOCKS:
        samples = jackknife_samples(stats, B, b)
        n = samples.shape[0]
        mean = samples.mean(dim=0)
        err = ((n - 1) / n * ((samples - mean) ** 2).sum(dim=0)).sqrt()
        sig[b] = {k: (mean[j].item(), err[j].item()) for j, k in enumerate(KEYS)}
        if b == 1:
            # Leave-one-out pseudo-values: each configuration's influence on the
            # statistic, in chain order. Their τ_int is what σ²(b)/σ²(1) tends to
            # (÷ 2) as b grows — the autocorrelation of the *quantity*, not of Ō.
            full = stats(torch.ones(B, dtype=torch.bool))
            pv = B * full - (B - 1) * samples
            pseudo_tau = {k: tau(pv[:, j]) for j, k in enumerate(KEYS)}
    return {"taus": taus, "rho": rhos, "pseudo_tau": pseudo_tau, "sigma": sig,
            "n_blocks": {b: -(-B // b) for b in BLOCKS}, "B": B}


def gate(per):
    fails = []
    for tag, res in per.items():
        for key, pub in (("dA0", PUBLISHED_DA0), ("dmeff1", PUBLISHED_DMEFF1)):
            if tag not in pub:
                continue
            got = res["sigma"][PRODUCTION][key]
            ok = all(abs(g - p) <= PUBLISHED_TOL for g, p in zip(got, pub[tag]))
            print(f"  gate {tag} {key}: {got[0]:+.4f} ± {got[1]:.4f} vs published "
                  f"{pub[tag][0]:+.3f} ± {pub[tag][1]:.3f}  {'ok' if ok else 'FAIL'}")
            if not ok:
                fails.append((tag, key))
    if fails:
        raise SystemExit(f"b = {PRODUCTION} does not reproduce the record: {fails}")


def reading(per):
    """Apply the pre-fixed reading; returns {key: (flagged, {b: (R̄_b, noise_b)})}."""
    n_ens = len(per)
    out = {}
    for k in KEYS:
        ratios = {}
        for b in BLOCKS:
            r = [res["sigma"][b][k][1] / res["sigma"][PRODUCTION][k][1] for res in per.values()]
            n_b = next(iter(per.values()))["n_blocks"][b]
            ratios[b] = (sum(r) / n_ens, err_of_err(n_b) / math.sqrt(n_ens))
        flagged = all(ratios[b][0] > 1.0 + ratios[b][1] for b in PLATEAU)
        out[k] = (flagged, ratios)
    return out


